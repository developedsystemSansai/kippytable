export type Remedy = {
  good: Color[];
  avoidColor: Color;
  carry: string;
  northern: string;
  topics: { cat: Cat; th: string; stars: number; example: string; todo: string; avoid: string; item: string }[];
};

const tierOf = (s: number): Tier => (s <= 2 ? "low" : s === 3 ? "mid" : "high");

export function remedies(r: Reading): Remedy {
  const own = ELEMENT_COLORS[r.sunEl];
  const clash = ELEMENT_COLORS[CLASH[r.sunEl]];
  const good: Color[] = [r.luckyColor];
  const ownPick = own.find((c) => c.name !== r.luckyColor.name) ?? own[0];
  good.push(ownPick);
  const avoidColor = clash.find((c) => c.name !== r.luckyColor.name && c.name !== ownPick.name) ?? clash[0];

  const topics = CATS.map((c) => {
    const bank = TOPIC[c.key][tierOf(r.stars[c.key])];
    const seed = `${r.date}|${c.key}|${r.sunSign}`;
    return {
      cat: c.key,
      th: c.th,
      stars: r.stars[c.key],
      example: bank.example[hashStr(seed) % bank.example.length],
      todo: bank.todo,
      avoid: bank.avoid,
      item: ITEMS[c.key][hashStr(`${seed}|item`) % ITEMS[c.key].length],
    };
  }).sort((a, b) => a.stars - b.stars); // weakest topic first: that is where the remedy helps most

  return { good, avoidColor, carry: ELEMENT_CARRY[r.sunEl], northern: NORTHERN[r.branch], topics };
}
