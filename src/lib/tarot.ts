export type Draw = { card: number; reversed: boolean };

function rnd(n: number): number {
  const a = new Uint32Array(1);
  crypto.getRandomValues(a);
  return a[0] % n;
}

/** Random spread without repeats. About 1 in 3 cards comes up reversed. */
export function drawSpread(count: number): Draw[] {
  const deck = TAROT.map((_, i) => i);
  for (let i = deck.length - 1; i > 0; i--) { const j = rnd(i + 1); [deck[i], deck[j]] = [deck[j], deck[i]]; }
  return deck.slice(0, count).map((card) => ({ card, reversed: rnd(3) === 0 }));
}

/** Same person + same day => same card, so the daily card is a ritual to come back to. */
export function dailyDraw(birthDate: string, date: string): Draw {
  const h = hashStr(`tarot|${birthDate}|${date}`);
  return { card: h % TAROT.length, reversed: ((h >>> 8) % 3) === 0 };
}

